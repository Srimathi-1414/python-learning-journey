#Student grade calculator

print("=========================")
print("Student Grade Calculator")
print("=========================")

#collect student details

student_name = input("Enter Student Name:")
roll_number = input("Enter roll number: ")

#Display student details

print("\n--------- STUDENT DETAILS ---------")

print("Name:", student_name)
print("Roll Number:", roll_number)

print("-----------------------------------")

# Subject details

subjects = ["English", "Mathematics", "Physics", "Chemistry", "Python"]

# Empty list to store marks

marks = []

# Collect marks for each subject

print("\n--------- ENTER SUBJECT MARKS ---------")

for subject in subjects:
    mark = int(input(f"Enter marks in {subject}: "))
    marks.append(mark)

# Display entered marks

print("\n--------- MARKS DETAILS ---------")

for i in range(len(subjects)):
    print(subjects[i], ":", marks[i])

# Calculate total and average

total = sum(marks)

average = total / len(marks)

average = round(average, 2)

# Display results

print("\n--------- MARKS SUMMARY ---------")

print("Total Marks:", total, "/ 500")
print("Average:", average, "%")

print("---------------------------------")

# Grade calculation

if average >= 90:
    grade = "A+"
elif average >= 80:
    grade = "A"
elif average >= 70:
    grade = "B"
elif average >= 60:
    grade = "C"
elif average >= 50:
    grade = "D"
else:
    grade = "F"

# PASS or FAIL calculation

passed = all(mark >= 35 for mark in marks)

if passed:
    result = "PASS"
else:
    result = "FAIL"

# Display grade and result

print("\n--------- GRADE REPORT ---------")
print("Grade:", grade)
print("Result:", result)
print("--------------------------------")

# Display complete student report

print("\n========== STUDENT REPORT ==========")

print("Student Name:", student_name)
print("Roll Number:", roll_number)

print("\nSubject-wise Marks:")

for i in range(len(subjects)):
    print(subjects[i], ":", marks[i])

print("\nTotal Marks:", total, "/ 500")
print("Average:", average, "%")
print("Grade:", grade)
print("Result:", result)

print("====================================")

# Collect marks with input validation

marks = []

print("\n--------- ENTER SUBJECT MARKS ---------")

for subject in subjects:

    while True:
        try:
            mark = int(input(f"Enter marks in {subject}: "))

            if 0 <= mark <= 100:
                marks.append(mark)
                break
            else:
                print("Invalid marks! Enter between 0 and 100.")

        except ValueError:
            print("Invalid input! Please enter a whole number.")

print("\nAll subject marks collected successfully!")
