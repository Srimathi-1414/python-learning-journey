import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("Libraries imported successfully!")

data = {
    "Student": [
        "Arun", "Priya", "Kavin", "Divya",
        "Rahul", "Meena", "Hari", "Nila"
    ],
    "Department": [
        "CSE", "AIML", "ECE", "AIML",
        "CSE", "ECE", "CSE", "AIML"
    ],
    "Marks": [85, 92, 78, 95, 88, 82, 75, 89],
    "Attendance": [90, 95, 82, 98, 85, 88, 80, 92]
}

df = pd.DataFrame(data)

print(df)

print("First five records:")
print(df.head())

print("\nDataset shape:")
print(df.shape)

print("\nDataset information:")
df.info()

print("\nStatistical summary:")
print(df.describe())

# Check missing values
print("Missing values:")
print(df.isnull().sum())

# Check duplicate records
print("\nDuplicate records:")
print(df.duplicated().sum())

# Remove duplicate records
df = df.drop_duplicates()

# Handle missing numerical values
df["Marks"] = df["Marks"].fillna(df["Marks"].mean())
df["Attendance"] = df["Attendance"].fillna(
    df["Attendance"].mean()
)

# Clean department names
df["Department"] = df["Department"].str.strip().str.upper()

print("Cleaned Dataset:")
print(df)

print("Total Students:", df["Student"].count())

print("Average Marks:", df["Marks"].mean())

print("Highest Marks:", df["Marks"].max())

print("Lowest Marks:", df["Marks"].min())

print("Average Attendance:", df["Attendance"].mean())

print("\nDepartment-wise Average Marks:")
print(df.groupby("Department")["Marks"].mean())

department_avg = df.groupby("Department")["Marks"].mean()

print(department_avg)

plt.figure(figsize=(7, 5))

plt.bar(department_avg.index, department_avg.values)

plt.xlabel("Department")
plt.ylabel("Average Marks")
plt.title("Department-wise Average Marks")

plt.show()

plt.figure(figsize=(8, 5))

plt.plot(df["Student"], df["Marks"], marker="o")

plt.xlabel("Students")
plt.ylabel("Marks")
plt.title("Student Performance Analysis")

plt.show()

department_count = df["Department"].value_counts()

plt.figure(figsize=(7, 5))

plt.pie(
    department_count.values,
    labels=department_count.index,
    autopct="%1.1f%%"
)

plt.title("Department-wise Student Distribution")

plt.show()

